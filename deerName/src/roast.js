  function sceneBatch(full, round, gender) {
    var all = [];
    for (var i = 0; i < SCENE_REVIEWS.length; i += 2) {
      var group = SCENE_REVIEWS[i + 1];
      for (var j = 0; j < group.length; j++) all.push(group[j]);
    }
    var chars = charsFor(full);
    var hard = chars.some(function (x) { return !x.it || (x.it.freq != null && x.it.freq <= 2); }) ||
      /乐|重|长|朝|曾|行|单|解|查|区|朴|缪|覃|仇|盖|翟|员|秘|繁|召/.test(full);
    var filtered = all.filter(function (line) {
      if (hard) return true;
      return !/念错|叫错|怎么读|偏旁|读音|读法|字没看错/.test(line);
    });
    if (filtered.length >= 6) all = filtered;
    var start = hash(full + '|scene|' + (round || 0) + '|' + (gender || 'u')) % all.length;
    var out = [];
    for (var n = 0; n < 3; n++) {
      var at = (start + n * 7) % all.length;
      if (out.indexOf(all[at]) === -1) out.push(all[at]);
    }
    return out;
  }

