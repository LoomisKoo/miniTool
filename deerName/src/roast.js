  /* 优先只看身份名——描述里的通用动词会造成误命中（把「收银」套到别的岗位）。
   * 命中多个时取最长的那个关键词，因为越长越具体：
   * 「直播间管理员」应该走管理员，而不是走「直播」。
   * 身份名没有线索时，才退一步看所在场景。 */
  function bestJab(title) {
    var best = -1, bestLen = 0;
    for (var i = 0; i < ROLE_JABS.length; i++) {
      var key = ROLE_JABS[i][0];
      if (key.length > bestLen && title.indexOf(key) !== -1) {
        best = i; bestLen = key.length;
      }
    }
    return best;
  }
  function jabIndex(story) {
    var idx = bestJab(String(story.title || ''));
    if (idx !== -1) return idx;
    return bestJab(String(story.place || ''));
  }
  function roleQuip(story, seed) {
    var idx = jabIndex(story);
    if (idx !== -1) return pick(ROLE_JABS[idx][1], seed, 'jab-' + idx);
    /* 用身份名当额外盐，避免同一个时代的不同岗位吐槽撞车 */
    var salt = seed + '|' + (story.title || '');
    var pool = story.dyn === '近未来' ? ROLE_JABS_FUTURE
      : (story.modern ? ROLE_JABS_MODERN : ROLE_JABS_ANCIENT);
    return pick(pool, salt, 'jab-generic');
  }
  function hasOwnJab(story) {
    return jabIndex(story) !== -1;
  }
  /* 一批描述是给江湖人物写的（桥洞下、常年落脚、来路不明），
   * 套在电报员、话务员身上就文不对题。命中这种就得丢掉。 */
  var MISFIT_TRADE = /常年落脚|从不轻易透露|不方便公开|不太体面|来路不明|没人说得清|说不清你到底|谁也没说清|出手大方/;
  var MISFIT_KEEP = /剑士|侠客|盗墓|相士|卜者|堪舆|掮客|线人|跑腿|镖|掌柜|牙人|江湖|游侠|算命|旧货|收废|典当|赌|走私|黑市|船夫|船娘|脚夫|更夫|夜哨|巡夜|樵夫|猎户/;
  function tradeReliable(story) {
    var t = String(story.trade || '');
    if (!MISFIT_TRADE.test(t)) return true;
    return MISFIT_KEEP.test(String(story.title || '') + String(story.place || ''));
  }
  /* 描述池是按场景批量生成的，很多条和身份名根本不是一回事
   * （照相馆化妆师配“替人跑腿、传话和保管东西”）。
   * 只有当描述里真的出现了身份名里的字，才认为这条描述值得展示。 */
  function tradeFits(title, trade) {
    title = String(title || '');
    trade = String(trade || '');
    if (title.length < 2 || !trade) return false;
    for (var i = 0; i + 2 <= title.length; i++) {
      if (trade.indexOf(title.substr(i, 2)) !== -1) return true;
    }
    return false;
  }
  /* 最终只输出一段话，读起来是一句锐评而不是「岗位说明书 + 附注」。
   * 岗位有自己的梗就直接吐槽，不解释；只有身份名和描述确实对得上时，
   * 才先交代一句这岗位在干嘛，再补一刀。 */
  function roleLine(story, seed) {
    var jab = roleQuip(story, seed);
    if (hasOwnJab(story)) return jab;
    if (!tradeReliable(story)) return jab;
    if (!tradeFits(story.title, story.trade)) return jab;
    return casualDesc(story) + '。' + jab;
  }

  /* 原始描述是“负责X、Y和Z”这种公文腔，去掉套话后读着更像人话。 */
  function casualDesc(story) {
    var text = roleSubtitle(story)
      .replace(/（[^）]*）/g, '')
      .replace(/^负责/, '')
      .replace(/^在[^，、]{2,10}负责/, '')
      .replace(/负责/g, '')
      .replace(/，也/g, '，还得')
      .replace(/和最后一道/, '和最后那道')
      .replace(/^[，、,；;：\s]+/, '');
    return text || String(story.trade || '');
  }

