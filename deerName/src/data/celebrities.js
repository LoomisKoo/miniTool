NM.rebuildCelebIndex = function () {
  var byKey = {}, byChar = {}, i, j, k, ch, list, keys, t;
  for (i = 0; i < NM.CELEBS.length; i++) {
    keys = NM.CELEBS[i].keys;
    for (j = 0; j < keys.length; j++) {
      k = keys[j];
      if (!k) continue;
      if (!byKey[k]) byKey[k] = [];
      byKey[k].push(i);
      for (t = 0; t < k.length; t++) {
        ch = k.charAt(t);
        if (!byChar[ch]) byChar[ch] = [];
        if (byChar[ch].indexOf(i) === -1) byChar[ch].push(i);
      }
    }
  }
  NM._celebByKey = byKey;
  NM._celebByChar = byChar;

  /* given: 名的字符串；chars: 名用字数组。返回最多 limit 条，整键优先。 */
  NM.celebsForName = function (given, chars, limit) {
    limit = limit || 3;
    given = String(given || '');
    chars = chars || given.split('');
    var seen = {}, out = [], score = {}, howMap = {}, idx, key, c, n;
    byKey = NM._celebByKey;

    function add(ix, sc, how) {
      if (seen[ix]) {
        if (sc > score[ix]) { score[ix] = sc; howMap[ix] = how; }
        return;
      }
      seen[ix] = 1;
      score[ix] = sc;
      howMap[ix] = how;
      out.push(ix);
    }

    var allKeys = Object.keys(byKey).sort(function (a, b) { return b.length - a.length; });
    for (n = 0; n < allKeys.length; n++) {
      key = allKeys[n];
      if (key.length < 2) continue;
      if (given.indexOf(key) === -1) continue;
      list = byKey[key];
      for (j = 0; j < list.length; j++) add(list[j], 100 + key.length, '同名「' + key + '」');
    }
    if (byKey[given]) {
      list = byKey[given];
      for (j = 0; j < list.length; j++) add(list[j], 200, '同名');
    }

    var strong = out.length;
    if (strong < limit) {
      for (n = 0; n < chars.length; n++) {
        c = chars[n];
        list = byKey[c];
        if (!list) continue;
        for (j = 0; j < list.length; j++) add(list[j], 20, '同字「' + c + '」');
      }
    }

    out.sort(function (a, b) { return score[b] - score[a]; });
    var hit = [];
    for (n = 0; n < out.length && hit.length < limit; n++) {
      idx = out[n];
      var s = NM.CELEBS[idx];
      hit.push({
        name: s.name, era: s.era, bio: s.bio,
        how: howMap[idx], score: score[idx]
      });
    }
    return hit;
  };
};

NM.rebuildCelebIndex();
