# 生成时与已收录的池子去重


def vec(a):
    return '[' + ', '.join(('%g' % x) for x in a) + ']'


def esc(s):
    return s.replace('\\', '\\\\').replace("'", "\\'")


HAVE = set(open('/tmp/enpool.txt', encoding='utf-8').read().split())
try:
    HAVE |= set(l.strip().split("'")[1] for l in open('src/data/names-en-more2.js', encoding='utf-8')
                if l.strip().startswith("['"))
except OSError:
    pass

lines = []
lines.append('/* 英文名 · 第四批')
lines.append(' * 前三批把「最常见的英文名」几乎铺满了，这批补的是不撞名的选择：')
lines.append(' * 北欧、斯拉夫、罗曼语、凯尔特，以及英语里少见但一读就会的老名。')
lines.append(' * 字段顺序同 packEn，见 names-en-more2.js 的说明。')
lines.append(' */')
lines.append('var NM = (window.NM = window.NM || {});')
lines.append('')
lines.append('NM.NAMES_EN = NM.NAMES_EN.concat(NM.packEn([')
seen = set()
n = 0
skip = 0
last_era = None
for (name, zh, ipa, org, era, g, snd, nick, tr, st, note) in EN3:
    if name in seen or name in HAVE:
        skip += 1
        continue
    seen.add(name)
    if era != last_era:
        lines.append('  /* ── %s ─────────────────────── */' % era)
        last_era = era
    n += 1
    lines.append("  ['%s', '%s', '%s', '%s', '%s', '%s', '%s', '%s',"
                 % (esc(name), esc(zh), esc(ipa), esc(org), era, g, esc(snd), esc(nick)))
    lines.append("    %s, %s, '%s']," % (vec(tr), vec(st), esc(note)))
lines.append(']));')
lines.append('')
open('src/data/names-en-more3.js', 'w', encoding='utf-8').write('\n'.join(lines))
print('写出 %d 条英文名，跳过已收录的 %d 条' % (n, skip))
