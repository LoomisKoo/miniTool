export function pickLine(action: string, temper: Temper, good: boolean): string {
  const pool = LINES[action]?.[temper]
  if (!pool) return '……'
  const arr = good ? pool.good : pool.bad
  return arr[Math.floor(Math.random() * arr.length)]
}

