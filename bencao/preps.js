/* pr 里能看出来的辅料 */
function matFromPrep(pr) {
  const t = pr || '';
  if (/蜜/.test(t)) return '蜜';
  if (/酒/.test(t)) return '酒';
  if (/醋/.test(t)) return '醋';
  if (/盐/.test(t)) return '盐';
  if (/姜/.test(t)) return '姜汁';
  return null;
}

